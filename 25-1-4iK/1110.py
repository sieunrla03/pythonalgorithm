N = int(input()) # 입력받은 수를 정수로 변환하여 N에 저장
M = N # 현재 계산 중인 수 M. 처음에는 입력값과 같음
cnt = 0 # 사이클 횟수를 세기 위한 변수

# 무한 반복하면서 사이클을 수행
while True:
    # 현재 수 M의 십의 자리와 일의 자리 분리
    a = M // 10      # 십의 자리 (예: 26이면 2)
    b = M % 10       # 일의 자리 (예: 26이면 6)

    # 두 자릿수를 더함 (예: 2 + 6 = 8)
    add = a + b

    # 새로운 수 생성: 현재 일의 자리 + (합의 일의 자리)
    # 예: 6(현재 b) + 8(합의 일의 자리) → 68
    M = b * 10 + (add % 10)

    # 사이클 횟수 증가
    cnt += 1

    # 원래 입력한 숫자와 같아졌다면 종료
    if M == N:
        break

# 총 반복 횟수 출력
print(cnt)